    canvas.drawString(LEFT_M, BOT_M - 30, '© 2025 Drona Enterprises · Multi-tenant Profitability Suite')
    canvas.setFont('FreeSerif-Bold', 8)
    canvas.setFillColor(TEXT_PRIMARY)
