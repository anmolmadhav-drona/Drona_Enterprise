def merge_cover(cover_pdf, body_pdf, output_pdf):
    from pypdf import PdfReader, PdfWriter
    from pypdf.generic import RectangleObject
    A4_W, A4_H = 595.28, 841.89

    def normalize(page):
        # Always re-scale the page box to exact A4 so the merged document has
        # uniform page sizes (pdf_qa.py rejects even sub-pt mismatches).
        box = page.mediabox
        w, h = float(box.width), float(box.height)
        if abs(w - A4_W) > 0.1 or abs(h - A4_H) > 0.1:
            page.scale_to(A4_W, A4_H)
        # Force the mediabox/cropbox to exact A4 (scale_to leaves a tiny drift)
        page.mediabox = RectangleObject([0, 0, A4_W, A4_H])
        page.cropbox = RectangleObject([0, 0, A4_W, A4_H])
        return page

    writer = PdfWriter()
    cover_page = PdfReader(cover_pdf).pages[0]
    writer.add_page(normalize(cover_page))
    for page in PdfReader(body_pdf).pages:
        writer.add_page(normalize(page))
    writer.add_metadata({
        '/Title': 'Drona Enterprises Profitability Suite — Technical Report',
        '/Author': 'Z.ai Engineering',
        '/Subject': 'Multi-Tenant Profitability SaaS Architecture',
        '/Creator': 'Z.ai PDF Skill (ReportLab)',
        '/Producer': 'ReportLab + pypdf',
    })
    with open(output_pdf, 'wb') as f:
        writer.write(f)
    print(f'Final PDF (cover + body merged): {output_pdf}')


