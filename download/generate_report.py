def add_heading(text, style, level=0):
    key = 'h_' + hashlib.md5(text.encode()).hexdigest()[:10]
    p = Paragraph(f'<a name="{key}"/>{text}', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def safe_keep(elements):
    """Wrap elements in KeepTogether only if they fit; otherwise split."""
    total_h = 0
    for el in elements:
        try:
            _, h = el.wrap(AVAIL_W, AVAIL_H)
            total_h += h
        except Exception:
            total_h += 30
    if total_h <= MAX_KEEP_H:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


def h1(text):
    return [CondPageBreak(H1_ORPHAN), add_heading(text, H1, level=0),
            HRFlowable(width="100%", thickness=1.4, color=ACCENT,
                       spaceBefore=2, spaceAfter=12)]


def h2(text):
    return [CondPageBreak(60), add_heading(text, H2, level=1)]


def h3(text):
    return [add_heading(text, H3, level=1)]


def p(text):
    # Use a non-breaking space before em-dashes so they never start a wrapped
    # line (pdf_qa.py flags em-dash line-start as a punctuation warning).
    text = text.replace(' — ', '\u00A0— ')
    return Paragraph(text, BODY)


def pl(text):
    text = text.replace(' — ', '\u00A0— ')
    return Paragraph(text, BODY_LEFT)


def bullet(text):
    text = text.replace(' — ', '\u00A0— ')
    return Paragraph(text, BULLET, bulletText=u'\u2022')


def caption(text):
    return Paragraph(text, CAPTION)


def fit_image(path, max_w=None, max_h=None):
    from PIL import Image as PILImage
    if max_w is None:
        max_w = AVAIL_W
    if max_h is None:
        max_h = AVAIL_H * 0.45
    pil = PILImage.open(path)
    ow, oh = pil.size
    rw = max_w / ow if ow > max_w else 1.0
    rh = max_h / oh if oh > max_h else 1.0
    r = min(rw, rh, 1.0)
    return Image(path, width=ow * r, height=oh * r)


def make_table(data_rows, col_ratios, header=True, h_align='CENTER'):
    """data_rows: list of lists of Paragraph or Image. col_ratios sum to 1.0."""
    col_widths = [r * AVAIL_W for r in col_ratios]
    t = Table(data_rows, colWidths=col_widths, hAlign=h_align, repeatRows=1 if header else 0)
    sty = [
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('GRID', (0, 0), (-1, -1), 0.35, BORDER),
    ]
    if header:
        sty += [
            ('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('TOPPADDING', (0, 0), (-1, 0), 7),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 7),
        ]
        for i in range(1, len(data_rows)):
            if i % 2 == 1:
                sty.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_ODD))
            else:
                sty.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_EVEN))
    t.setStyle(TableStyle(sty))
    return t


def callout(value, label, color=ACCENT, width=130):
    val_style = ParagraphStyle('cv', parent=CALLOUT_VAL, textColor=color)
    cell = Table(
        [[Paragraph(value, val_style)],
         [Paragraph(label, CALLOUT_LBL)]],
        colWidths=[width],
    )
    cell.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
        ('BOX', (0, 0), (-1, -1), 0.6, BORDER),
        ('LINEBEFORE', (0, 0), (0, -1), 3, color),
        ('TOPPADDING', (0, 0), (-1, -1), 8),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
        ('LEFTPADDING', (0, 0), (-1, -1), 10),
        ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]))
    return cell


def callout_row(items, total_width=None):
    """items = list of (value, label, color) tuples. Render side by side."""
    if total_width is None:
        total_width = AVAIL_W
    n = len(items)
    col_w = total_width / n
    cells = [callout(v, l, c, width=col_w - 8) for v, l, c in items]
    t = Table([cells], colWidths=[col_w] * n, hAlign='CENTER')
    t.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 3),
        ('RIGHTPADDING', (0, 0), (-1, -1), 3),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
    ]))
    return t


