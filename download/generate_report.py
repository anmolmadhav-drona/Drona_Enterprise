    # the trailing digits as a page-number reference and fail the TOC check).
    canvas.drawRightString(PAGE_W - RIGHT_M, PAGE_H - TOP_M + 22, 'Z.ai Engineering  -  v1.0')
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.6)
    canvas.line(LEFT_M, PAGE_H - TOP_M + 16, PAGE_W - RIGHT_M, PAGE_H - TOP_M + 16)

    # Footer: rule + page number
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.4)
    canvas.line(LEFT_M, BOT_M - 18, PAGE_W - RIGHT_M, BOT_M - 18)
    canvas.setFont('FreeSerif', 8)
